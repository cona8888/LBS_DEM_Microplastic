%RUN_NATIVE_MATDEM_HYDROMECHANICAL_CASE Execute all native MatDEM stages.
projectRoot = string(fileparts(fileparts(mfilename('fullpath'))));
config = native_matdem_hydromechanical_config(projectRoot);
environment = setup_matdem_microplastic( ...
    MatDEMRoot=config.engine.matdem_root);
assert(strlength(environment.pore3d_path) > 0, ...
    'matdem_microplastic:Pore3dNotExposed', ...
    ['Native run stopped before specimen generation: pore3d is not ' ...
     'visible in this MATLAB session. Use the standalone MatDEM runtime ' ...
     'that exposes pore3d, or obtain the pore module from MatDEM.']);
assert(environment.gpu_available, ...
    'matdem_microplastic:NativeGPUUnavailable', ...
    ['Native run stopped before specimen generation: GPU support is not ' ...
     'visible (%s). Use the GPU-enabled standalone MatDEM runtime or ' ...
     'install MATLAB Parallel Computing Toolbox.'], ...
    environment.gpu_message);
native_matdem_prepare_specimen(projectRoot);
native_matdem_initialize_pore3d(projectRoot);
native_matdem_run_coupled_permeability(projectRoot);
