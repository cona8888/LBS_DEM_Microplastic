function result = simulate_microplastic_permeability_study(config)
%SIMULATE_MICROPLASTIC_PERMEABILITY_STUDY Reduced fixed/mobile mechanism toy.
%
% Fixed spherical inclusions modify the solid-volume specific surface used by
% Kozeny-Carman. Mobile particles obey an inlet-retention-detachment balance;
% retained-capacity saturation reduces permeability. This model is intended
% for mechanism tests and calibration design, not as a MatDEM pore prediction.

arguments
    config (1,1) struct
end

validateConfig(config);

fraction = config.fixed_volume_fraction(:);
porosity = config.clean_porosity + ...
    config.porosity_change_per_unit_fraction .* fraction;
solidSpecificSurface = 6 .* ( ...
    (1 - fraction) ./ config.sand_diameter_m + ...
    fraction ./ config.microplastic_diameter_m);
intrinsicPermeability = porosity.^3 ./ ( ...
    config.kozeny_constant .* solidSpecificSurface.^2 .* ...
    (1 - porosity).^2);
hydraulicConductivity = intrinsicPermeability .* ...
    config.water_density_kg_per_m3 .* config.gravity_m_per_s2 ./ ...
    config.water_dynamic_viscosity_pa_s;

cleanSphereBenchmark = config.sand_diameter_m^2 .* ...
    config.clean_porosity^3 ./ (180 .* (1 - config.clean_porosity)^2);
cleanBenchmarkError = abs(intrinsicPermeability(1) - ...
    cleanSphereBenchmark) ./ cleanSphereBenchmark;
assert(cleanBenchmarkError < 1.0e-12, ...
    'matdem_microplastic:CleanBenchmarkFailed', ...
    'Clean Kozeny-Carman benchmark error is %.3e.', cleanBenchmarkError);

area = pi .* config.specimen_diameter_m^2 ./ 4;
fixedFlow = hydraulicConductivity .* config.hydraulic_gradient .* area;
protocols = simulate_hydraulic_protocols(config, intrinsicPermeability);

mobile = struct();
if config.mobile_enabled
    mobile = runMobileRetention(config, intrinsicPermeability, area);
    assert(max(mobile.mass_balance_relative_error, [], 'all') < 1.0e-12, ...
        'matdem_microplastic:MobileMassBalanceFailed', ...
        'Mobile-particle mass-balance error exceeds tolerance.');
end

summary = struct();
summary.status = "pass";
summary.backend = string(config.backend);
summary.scope = "reduced fixed-inclusion and mobile-clogging mechanism study";
summary.matdem_pore_prediction = false;
summary.content_definition = string(config.content_definition);
summary = copyOptionalCaseMetadata(summary, config);
summary.hydraulic_protocols = string(config.hydraulic_protocols);
summary.specimen_diameter_m = config.specimen_diameter_m;
summary.specimen_height_m = config.specimen_length_m;
summary.specimen_diameter_to_sand_diameter = ...
    config.specimen_diameter_m ./ config.sand_diameter_m;
summary.specimen_height_to_sand_diameter = ...
    config.specimen_length_m ./ config.sand_diameter_m;
sampleVolume = area .* config.specimen_length_m;
grainVolume = pi .* config.sand_diameter_m^3 ./ 6;
summary.approximate_clean_sand_particle_count = ...
    (1 - config.clean_porosity) .* sampleVolume ./ grainVolume;
summary.fixed_volume_fraction = fraction;
summary.porosity = porosity;
summary.intrinsic_permeability_m2 = intrinsicPermeability;
summary.hydraulic_conductivity_m_per_s = hydraulicConductivity;
summary.fixed_permeability_ratio = intrinsicPermeability ./ ...
    intrinsicPermeability(1);
summary.clean_sphere_benchmark_m2 = cleanSphereBenchmark;
summary.clean_benchmark_relative_error = cleanBenchmarkError;
summary.fixed_flow_rate_m3_per_s = fixedFlow;
summary.constant_head_recovery_relative_error = ...
    protocols.constant_head.recovery_relative_error;
summary.falling_head_time_to_terminal_head_s = ...
    protocols.falling_head.time_to_terminal_head_s;
summary.falling_head_recovery_relative_error = ...
    protocols.falling_head.recovery_relative_error;
summary.falling_head_finest_normalized_error = ...
    protocols.falling_head.verification_normalized_error(end);
if config.mobile_enabled
    summary.mobile_final_permeability_ratio_to_fixed = ...
        mobile.intrinsic_permeability_m2(end,:).' ./ intrinsicPermeability;
    summary.mobile_final_retained_mass_kg = ...
        mobile.retained_mass_kg(end,:).';
    summary.mobile_mass_balance_relative_error = ...
        mobile.mass_balance_relative_error(:);
    summary.falling_head_mobile_final_permeability_ratio_to_fixed = ...
        protocols.falling_head.mobile.final_permeability_ratio_to_fixed;
    summary.falling_head_mobile_final_retained_mass_kg = ...
        protocols.falling_head.mobile.final_retained_mass_kg;
    summary.falling_head_mobile_mass_balance_relative_error = ...
        protocols.falling_head.mobile.mass_balance_relative_error;
else
    summary.mobile_final_permeability_ratio_to_fixed = [];
    summary.mobile_final_retained_mass_kg = [];
    summary.mobile_mass_balance_relative_error = [];
end
summary.timestamp_utc = string(datetime('now', 'TimeZone', 'UTC', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ssXXX'));

result = struct();
result.summary = summary;
result.fixed = struct();
result.fixed.volume_fraction = fraction;
result.fixed.porosity = porosity;
result.fixed.solid_specific_surface_per_m = solidSpecificSurface;
result.fixed.intrinsic_permeability_m2 = intrinsicPermeability;
result.fixed.hydraulic_conductivity_m_per_s = hydraulicConductivity;
result.fixed.flow_rate_m3_per_s = fixedFlow;
result.mobile = mobile;
result.protocols = protocols;

if config.write_results
    writeResult(config.output_directory, result, config);
end

fprintf(['MICROPLASTIC_REDUCED_STUDY_PASS cases=%d clean_k_m2=%.9g ' ...
    'fixed_last_ratio=%.9g mobile_last_ratio=%.9g\n'], ...
    numel(fraction), intrinsicPermeability(1), ...
    summary.fixed_permeability_ratio(end), ...
    finalMobileRatio(summary));
end

function summary = copyOptionalCaseMetadata(summary, config)
fields = ["case_name", "calibration_status", "sand_name", ...
    "sand_d10_m", "sand_d50_m", "sand_d60_m", ...
    "sand_uniformity_coefficient", "sand_minimum_void_ratio", ...
    "sand_maximum_void_ratio", "sand_relative_density", ...
    "sand_void_ratio", "microplastic_to_sand_size_ratio", ...
    "microplastic_diameter_m", "microplastic_shape", ...
    "microplastic_content_status", "literature_source", ...
    "literature_source_url"];
for fieldName = fields
    if isfield(config, fieldName)
        summary.(fieldName) = config.(fieldName);
    end
end
end

function mobile = runMobileRetention(config, fixedPermeability, area)
time = (0:config.mobile_time_step_s:config.mobile_duration_s).';
caseCount = numel(fixedPermeability);
stepCount = numel(time) - 1;

retained = zeros(stepCount + 1, caseCount);
permeability = zeros(stepCount + 1, caseCount);
permeability(1,:) = fixedPermeability(:).';
flow = zeros(stepCount, caseCount);
inletMass = zeros(stepCount, caseCount);
effluentMass = zeros(stepCount, caseCount);
captureFraction = 1 - exp( ...
    -config.mobile_filtration_coefficient_per_m .* ...
    config.specimen_length_m);

for stepIndex = 1:stepCount
    conductivity = permeability(stepIndex,:) .* ...
        config.water_density_kg_per_m3 .* config.gravity_m_per_s2 ./ ...
        config.water_dynamic_viscosity_pa_s;
    flow(stepIndex,:) = conductivity .* config.hydraulic_gradient .* area;
    inletMass(stepIndex,:) = flow(stepIndex,:) .* ...
        config.mobile_inlet_concentration_kg_per_m3 .* ...
        config.mobile_time_step_s;

    capacityFraction = retained(stepIndex,:) ./ ...
        config.mobile_retention_capacity_kg;
    potentialCapture = inletMass(stepIndex,:) .* captureFraction .* ...
        max(0, 1 - capacityFraction);
    potentialDetachment = retained(stepIndex,:) .* ...
        config.mobile_detachment_rate_per_s .* ...
        config.mobile_time_step_s;
    trialRetained = retained(stepIndex,:) + potentialCapture - ...
        potentialDetachment;
    retained(stepIndex + 1,:) = min( ...
        config.mobile_retention_capacity_kg, max(0, trialRetained));
    retainedIncrement = retained(stepIndex + 1,:) - ...
        retained(stepIndex,:);
    effluentMass(stepIndex,:) = inletMass(stepIndex,:) - ...
        retainedIncrement;

    saturation = retained(stepIndex + 1,:) ./ ...
        config.mobile_retention_capacity_kg;
    permeabilityRatio = max( ...
        config.mobile_minimum_permeability_ratio, ...
        (1 - saturation).^config.mobile_clogging_exponent);
    permeability(stepIndex + 1,:) = fixedPermeability(:).' .* ...
        permeabilityRatio;
end

cumulativeInlet = sum(inletMass, 1);
cumulativeEffluent = sum(effluentMass, 1);
balanceResidual = cumulativeInlet - cumulativeEffluent - retained(end,:);
balanceRelativeError = abs(balanceResidual) ./ ...
    max(cumulativeInlet, realmin);

mobile = struct();
mobile.time_s = time;
mobile.intrinsic_permeability_m2 = permeability;
mobile.retained_mass_kg = retained;
mobile.flow_rate_m3_per_s = flow;
mobile.inlet_mass_per_step_kg = inletMass;
mobile.effluent_mass_per_step_kg = effluentMass;
mobile.cumulative_inlet_mass_kg = cumulativeInlet;
mobile.cumulative_effluent_mass_kg = cumulativeEffluent;
mobile.mass_balance_relative_error = balanceRelativeError;
end

function validateConfig(config)
required = ["backend", "content_definition", "sand_diameter_m", ...
    "microplastic_diameter_m", "clean_porosity", ...
    "porosity_change_per_unit_fraction", "kozeny_constant", ...
    "fixed_volume_fraction", "water_density_kg_per_m3", ...
    "water_dynamic_viscosity_pa_s", "gravity_m_per_s2", ...
    "specimen_diameter_m", "specimen_length_m", ...
    "hydraulic_gradient", "mobile_enabled", "mobile_duration_s", ...
    "mobile_time_step_s", "mobile_inlet_concentration_kg_per_m3", ...
    "mobile_filtration_coefficient_per_m", ...
    "mobile_detachment_rate_per_s", "mobile_retention_capacity_kg", ...
    "mobile_clogging_exponent", ...
    "mobile_minimum_permeability_ratio", "write_results", ...
    "output_directory"];
for fieldName = required
    assert(isfield(config, fieldName), ...
        'matdem_microplastic:MissingConfig', ...
        'Missing configuration field: %s', fieldName);
end

positiveFields = ["sand_diameter_m", "microplastic_diameter_m", ...
    "kozeny_constant", "water_density_kg_per_m3", ...
    "water_dynamic_viscosity_pa_s", "gravity_m_per_s2", ...
    "specimen_diameter_m", "specimen_length_m", ...
    "hydraulic_gradient", "mobile_duration_s", "mobile_time_step_s", ...
    "mobile_inlet_concentration_kg_per_m3", ...
    "mobile_filtration_coefficient_per_m", ...
    "mobile_retention_capacity_kg", "mobile_clogging_exponent"];
for fieldName = positiveFields
    value = config.(fieldName);
    assert(isscalar(value) && isfinite(value) && value > 0, ...
        'matdem_microplastic:InvalidConfig', ...
        '%s must be positive and finite.', fieldName);
end
assert(config.clean_porosity > 0 && config.clean_porosity < 1, ...
    'matdem_microplastic:InvalidConfig', ...
    'clean_porosity must be between zero and one.');
fraction = config.fixed_volume_fraction;
assert(isvector(fraction) && all(isfinite(fraction)) && ...
    all(fraction >= 0 & fraction < 1) && fraction(1) == 0, ...
    'matdem_microplastic:InvalidConfig', ...
    'fixed_volume_fraction must start at zero and remain in [0,1).');
porosity = config.clean_porosity + ...
    config.porosity_change_per_unit_fraction .* fraction;
assert(all(porosity > 0 & porosity < 1), ...
    'matdem_microplastic:InvalidConfig', ...
    'All derived porosities must remain between zero and one.');
assert(config.mobile_time_step_s <= config.mobile_duration_s && ...
    mod(config.mobile_duration_s, config.mobile_time_step_s) == 0, ...
    'matdem_microplastic:InvalidConfig', ...
    'Mobile duration must be an integer multiple of the time step.');
assert(config.mobile_detachment_rate_per_s >= 0 && ...
    isfinite(config.mobile_detachment_rate_per_s), ...
    'matdem_microplastic:InvalidConfig', ...
    'mobile_detachment_rate_per_s must be finite and nonnegative.');
assert(config.mobile_minimum_permeability_ratio > 0 && ...
    config.mobile_minimum_permeability_ratio <= 1, ...
    'matdem_microplastic:InvalidConfig', ...
    'mobile_minimum_permeability_ratio must be in (0,1].');
end

function ratio = finalMobileRatio(summary)
if isempty(summary.mobile_final_permeability_ratio_to_fixed)
    ratio = NaN;
else
    ratio = summary.mobile_final_permeability_ratio_to_fixed(end);
end
end

function writeResult(outputDirectory, result, config)
if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end
save(fullfile(outputDirectory, 'microplastic_reduced_study_result.mat'), ...
    'result', 'config');

summaryPath = fullfile(outputDirectory, ...
    'microplastic_reduced_study_summary.json');
fileId = fopen(summaryPath, 'w');
assert(fileId >= 0, 'matdem_microplastic:ResultWriteFailed', ...
    'Could not open result JSON for writing: %s', summaryPath);
cleanupFile = onCleanup(@() fclose(fileId));
fprintf(fileId, '%s\n', jsonencode(result.summary, PrettyPrint=true));

fixedTable = table(result.fixed.volume_fraction, result.fixed.porosity, ...
    result.fixed.solid_specific_surface_per_m, ...
    result.fixed.intrinsic_permeability_m2, ...
    result.fixed.hydraulic_conductivity_m_per_s, ...
    result.fixed.flow_rate_m3_per_s, ...
    'VariableNames', ["microplastic_solid_volume_fraction", "porosity", ...
    "solid_specific_surface_per_m", "intrinsic_permeability_m2", ...
    "hydraulic_conductivity_m_per_s", "flow_rate_m3_per_s"]);
writetable(fixedTable, fullfile(outputDirectory, ...
    'fixed_inclusion_parametric_summary.csv'));

if config.mobile_enabled
    caseCount = numel(result.fixed.volume_fraction);
    rowCount = numel(result.mobile.time_s) .* caseCount;
    timeColumn = repmat(result.mobile.time_s, caseCount, 1);
    fractionColumn = repelem(result.fixed.volume_fraction, ...
        numel(result.mobile.time_s));
    permeabilityColumn = reshape(result.mobile.intrinsic_permeability_m2, ...
        rowCount, 1);
    retainedColumn = reshape(result.mobile.retained_mass_kg, rowCount, 1);
    mobileTable = table(timeColumn, fractionColumn, ...
        permeabilityColumn, retainedColumn, ...
        'VariableNames', ["time_s", ...
        "fixed_microplastic_solid_volume_fraction", ...
        "intrinsic_permeability_m2", "retained_mobile_mass_kg"]);
    writetable(mobileTable, fullfile(outputDirectory, ...
        'mobile_clogging_time_history.csv'));

    fallingMobile = result.protocols.falling_head.mobile;
    protocolTable = table(result.fixed.volume_fraction, ...
        result.protocols.constant_head.flow_rate_m3_per_s, ...
        result.protocols.falling_head.time_to_terminal_head_s, ...
        fallingMobile.duration_s, ...
        fallingMobile.final_permeability_ratio_to_fixed, ...
        fallingMobile.final_retained_mass_kg, ...
        fallingMobile.mass_balance_relative_error, ...
        'VariableNames', ["microplastic_solid_volume_fraction", ...
        "constant_head_flow_rate_m3_per_s", ...
        "fixed_falling_head_duration_s", ...
        "mobile_falling_head_duration_s", ...
        "mobile_falling_head_final_permeability_ratio", ...
        "mobile_falling_head_final_retained_mass_kg", ...
        "mobile_falling_head_mass_balance_relative_error"]);
    writetable(protocolTable, fullfile(outputDirectory, ...
        'hydraulic_protocol_summary.csv'));

    historyParts = cell(caseCount, 1);
    for caseIndex = 1:caseCount
        caseTime = fallingMobile.time_s{caseIndex};
        caseRowCount = numel(caseTime);
        historyParts{caseIndex} = table( ...
            repmat(result.fixed.volume_fraction(caseIndex), ...
            caseRowCount, 1), caseTime, ...
            fallingMobile.head_m{caseIndex}, ...
            fallingMobile.intrinsic_permeability_m2{caseIndex}, ...
            fallingMobile.retained_mass_kg{caseIndex}, ...
            'VariableNames', [ ...
            "fixed_microplastic_solid_volume_fraction", "time_s", ...
            "head_m", "intrinsic_permeability_m2", ...
            "retained_mobile_mass_kg"]);
    end
    writetable(vertcat(historyParts{:}), fullfile(outputDirectory, ...
        'falling_head_mobile_time_history.csv'));
end
end
