function protocols = simulate_hydraulic_protocols(config, fixedPermeability)
%SIMULATE_HYDRAULIC_PROTOCOLS Constant- and falling-head reduced tests.
%
% The fixed-bed results are analytical Darcy-law checks. The mobile
% falling-head calculation couples explicit head decay to the same retained
% microplastic mass balance used by the constant-head mechanism toy.

arguments
    config (1,1) struct
    fixedPermeability (:,1) double
end

validateProtocolConfig(config, fixedPermeability);

sampleArea = pi .* config.specimen_diameter_m^2 ./ 4;
standpipeArea = pi .* config.falling_head_standpipe_diameter_m^2 ./ 4;
conductivity = fixedPermeability .* config.water_density_kg_per_m3 .* ...
    config.gravity_m_per_s2 ./ config.water_dynamic_viscosity_pa_s;

constantHeadLoss = config.hydraulic_gradient .* config.specimen_length_m;
constantFlow = conductivity .* sampleArea .* config.hydraulic_gradient;
constantRecoveredConductivity = constantFlow .* ...
    config.specimen_length_m ./ (sampleArea .* constantHeadLoss);
constantRecoveredPermeability = constantRecoveredConductivity .* ...
    config.water_dynamic_viscosity_pa_s ./ ...
    (config.water_density_kg_per_m3 .* config.gravity_m_per_s2);
constantError = abs(constantRecoveredPermeability - fixedPermeability) ./ ...
    fixedPermeability;

headRatio = config.falling_head_initial_head_m ./ ...
    config.falling_head_terminal_head_m;
fallingTimeConstant = standpipeArea .* config.specimen_length_m ./ ...
    (conductivity .* sampleArea);
fallingTargetTime = fallingTimeConstant .* log(headRatio);
fallingRecoveredConductivity = standpipeArea .* ...
    config.specimen_length_m ./ (sampleArea .* fallingTargetTime) .* ...
    log(headRatio);
fallingRecoveredPermeability = fallingRecoveredConductivity .* ...
    config.water_dynamic_viscosity_pa_s ./ ...
    (config.water_density_kg_per_m3 .* config.gravity_m_per_s2);
fallingError = abs(fallingRecoveredPermeability - fixedPermeability) ./ ...
    fixedPermeability;

fractions = config.falling_head_verification_time_step_fractions(:);
verificationHeadRatio = zeros(size(fractions));
for index = 1:numel(fractions)
    stepCount = round(1 ./ fractions(index));
    verificationHeadRatio(index) = (1 - fractions(index)).^stepCount;
end
verificationError = abs(verificationHeadRatio - exp(-1));
assert(all(diff(verificationError) < 0), ...
    'matdem_microplastic:FallingHeadConvergenceFailed', ...
    'Falling-head explicit-Euler error did not decrease with refinement.');
assert(verificationError(end) < 1.0e-2, ...
    'matdem_microplastic:FallingHeadAccuracyFailed', ...
    'Finest falling-head normalized error is %.3e.', ...
    verificationError(end));
assert(max(constantError) < 1.0e-12, ...
    'matdem_microplastic:ConstantHeadRecoveryFailed', ...
    'Constant-head permeability recovery error is %.3e.', ...
    max(constantError));
assert(max(fallingError) < 1.0e-12, ...
    'matdem_microplastic:FallingHeadRecoveryFailed', ...
    'Falling-head permeability recovery error is %.3e.', ...
    max(fallingError));

protocols = struct();
protocols.sample_area_m2 = sampleArea;
protocols.standpipe_area_m2 = standpipeArea;
protocols.constant_head = struct();
protocols.constant_head.head_loss_m = constantHeadLoss;
protocols.constant_head.pressure_drop_pa = ...
    config.water_density_kg_per_m3 .* config.gravity_m_per_s2 .* ...
    constantHeadLoss;
protocols.constant_head.flow_rate_m3_per_s = constantFlow;
protocols.constant_head.recovered_intrinsic_permeability_m2 = ...
    constantRecoveredPermeability;
protocols.constant_head.recovery_relative_error = constantError;

protocols.falling_head = struct();
protocols.falling_head.initial_head_m = ...
    config.falling_head_initial_head_m;
protocols.falling_head.terminal_head_m = ...
    config.falling_head_terminal_head_m;
protocols.falling_head.time_constant_s = fallingTimeConstant;
protocols.falling_head.time_to_terminal_head_s = fallingTargetTime;
protocols.falling_head.recovered_intrinsic_permeability_m2 = ...
    fallingRecoveredPermeability;
protocols.falling_head.recovery_relative_error = fallingError;
protocols.falling_head.verification_time_step_fraction = fractions;
protocols.falling_head.verification_head_ratio_at_one_time_constant = ...
    verificationHeadRatio;
protocols.falling_head.verification_normalized_error = verificationError;

if config.mobile_enabled
    protocols.falling_head.mobile = runMobileFallingHead( ...
        config, fixedPermeability, sampleArea, standpipeArea, ...
        fallingTimeConstant);
    assert(max(protocols.falling_head.mobile.mass_balance_relative_error) ...
        < 1.0e-12, ...
        'matdem_microplastic:FallingHeadMobileMassBalanceFailed', ...
        'Falling-head mobile mass-balance error exceeds tolerance.');
    assert(all(protocols.falling_head.mobile.terminal_head_reached), ...
        'matdem_microplastic:FallingHeadTargetNotReached', ...
        'At least one falling-head mobile case did not reach terminal head.');
end
end

function mobile = runMobileFallingHead(config, fixedPermeability, ...
    sampleArea, standpipeArea, initialTimeConstant)
caseCount = numel(fixedPermeability);
captureFraction = 1 - exp( ...
    -config.mobile_filtration_coefficient_per_m .* ...
    config.specimen_length_m);

timeHistory = cell(caseCount, 1);
headHistory = cell(caseCount, 1);
permeabilityHistory = cell(caseCount, 1);
retainedHistory = cell(caseCount, 1);
duration = zeros(caseCount, 1);
retainedFinal = zeros(caseCount, 1);
permeabilityFinal = zeros(caseCount, 1);
balanceError = zeros(caseCount, 1);
terminalReached = false(caseCount, 1);
stepCounts = zeros(caseCount, 1);

for caseIndex = 1:caseCount
    timeStep = config.falling_head_mobile_time_step_fraction .* ...
        initialTimeConstant(caseIndex);
    time = 0;
    head = config.falling_head_initial_head_m;
    retained = 0;
    permeability = fixedPermeability(caseIndex);
    cumulativeInlet = 0;
    cumulativeEffluent = 0;

    localTime = zeros(config.falling_head_maximum_steps + 1, 1);
    localHead = zeros(config.falling_head_maximum_steps + 1, 1);
    localPermeability = zeros(config.falling_head_maximum_steps + 1, 1);
    localRetained = zeros(config.falling_head_maximum_steps + 1, 1);
    localHead(1) = head;
    localPermeability(1) = permeability;

    for stepIndex = 1:config.falling_head_maximum_steps
        conductivity = permeability .* config.water_density_kg_per_m3 .* ...
            config.gravity_m_per_s2 ./ ...
            config.water_dynamic_viscosity_pa_s;
        flow = conductivity .* sampleArea .* head ./ ...
            config.specimen_length_m;
        availableVolume = standpipeArea .* ...
            (head - config.falling_head_terminal_head_m);
        transferredVolume = min(flow .* timeStep, availableVolume);
        assert(isfinite(transferredVolume) && transferredVolume >= 0, ...
            'matdem_microplastic:InvalidFallingHeadFlow', ...
            'Invalid falling-head transferred volume.');
        if transferredVolume == 0
            break
        end
        actualTimeStep = transferredVolume ./ flow;
        inletMass = transferredVolume .* ...
            config.mobile_inlet_concentration_kg_per_m3;

        capacityFraction = retained ./ ...
            config.mobile_retention_capacity_kg;
        potentialCapture = inletMass .* captureFraction .* ...
            max(0, 1 - capacityFraction);
        potentialDetachment = retained .* ...
            config.mobile_detachment_rate_per_s .* actualTimeStep;
        updatedRetained = min(config.mobile_retention_capacity_kg, ...
            max(0, retained + potentialCapture - potentialDetachment));
        retainedIncrement = updatedRetained - retained;
        effluentMass = inletMass - retainedIncrement;

        cumulativeInlet = cumulativeInlet + inletMass;
        cumulativeEffluent = cumulativeEffluent + effluentMass;
        retained = updatedRetained;
        saturation = retained ./ config.mobile_retention_capacity_kg;
        permeabilityRatio = max( ...
            config.mobile_minimum_permeability_ratio, ...
            (1 - saturation).^config.mobile_clogging_exponent);
        permeability = fixedPermeability(caseIndex) .* permeabilityRatio;
        head = head - transferredVolume ./ standpipeArea;
        time = time + actualTimeStep;

        historyIndex = stepIndex + 1;
        localTime(historyIndex) = time;
        localHead(historyIndex) = head;
        localPermeability(historyIndex) = permeability;
        localRetained(historyIndex) = retained;

        if head <= config.falling_head_terminal_head_m * (1 + 1.0e-12)
            terminalReached(caseIndex) = true;
            stepCounts(caseIndex) = stepIndex;
            break
        end
    end

    if stepCounts(caseIndex) == 0
        stepCounts(caseIndex) = config.falling_head_maximum_steps;
    end
    used = 1:(stepCounts(caseIndex) + 1);
    timeHistory{caseIndex} = localTime(used);
    headHistory{caseIndex} = localHead(used);
    permeabilityHistory{caseIndex} = localPermeability(used);
    retainedHistory{caseIndex} = localRetained(used);
    duration(caseIndex) = time;
    retainedFinal(caseIndex) = retained;
    permeabilityFinal(caseIndex) = permeability;
    balanceResidual = cumulativeInlet - cumulativeEffluent - retained;
    balanceError(caseIndex) = abs(balanceResidual) ./ ...
        max(cumulativeInlet, realmin);
end

mobile = struct();
mobile.time_s = timeHistory;
mobile.head_m = headHistory;
mobile.intrinsic_permeability_m2 = permeabilityHistory;
mobile.retained_mass_kg = retainedHistory;
mobile.duration_s = duration;
mobile.final_retained_mass_kg = retainedFinal;
mobile.final_intrinsic_permeability_m2 = permeabilityFinal;
mobile.final_permeability_ratio_to_fixed = permeabilityFinal ./ ...
    fixedPermeability;
mobile.mass_balance_relative_error = balanceError;
mobile.terminal_head_reached = terminalReached;
mobile.step_count = stepCounts;
end

function validateProtocolConfig(config, fixedPermeability)
required = ["specimen_diameter_m", "specimen_length_m", ...
    "hydraulic_protocols", "hydraulic_gradient", ...
    "falling_head_standpipe_diameter_m", ...
    "falling_head_initial_head_m", "falling_head_terminal_head_m", ...
    "falling_head_verification_time_step_fractions", ...
    "falling_head_mobile_time_step_fraction", ...
    "falling_head_maximum_steps", "water_density_kg_per_m3", ...
    "water_dynamic_viscosity_pa_s", "gravity_m_per_s2", ...
    "mobile_enabled", "mobile_inlet_concentration_kg_per_m3", ...
    "mobile_filtration_coefficient_per_m", ...
    "mobile_detachment_rate_per_s", "mobile_retention_capacity_kg", ...
    "mobile_clogging_exponent", "mobile_minimum_permeability_ratio"];
for fieldName = required
    assert(isfield(config, fieldName), ...
        'matdem_microplastic:MissingConfig', ...
        'Missing protocol configuration field: %s', fieldName);
end
assert(isequal(sort(string(config.hydraulic_protocols(:))), ...
    sort(["constant_head"; "falling_head"])), ...
    'matdem_microplastic:InvalidProtocols', ...
    'Both constant_head and falling_head protocols are required.');
assert(all(isfinite(fixedPermeability)) && all(fixedPermeability > 0), ...
    'matdem_microplastic:InvalidPermeability', ...
    'Fixed permeability values must be positive and finite.');
assert(config.falling_head_initial_head_m > ...
    config.falling_head_terminal_head_m && ...
    config.falling_head_terminal_head_m > 0, ...
    'matdem_microplastic:InvalidFallingHead', ...
    'Falling-head levels must satisfy initial > terminal > 0.');
fractions = config.falling_head_verification_time_step_fractions(:);
assert(numel(fractions) >= 3 && all(diff(fractions) < 0) && ...
    all(fractions > 0 & fractions < 1), ...
    'matdem_microplastic:InvalidFallingHeadRefinement', ...
    'Supply at least three decreasing time-step fractions in (0,1).');
assert(config.falling_head_mobile_time_step_fraction > 0 && ...
    config.falling_head_mobile_time_step_fraction < 1, ...
    'matdem_microplastic:InvalidFallingHeadTimeStep', ...
    'Falling-head mobile time-step fraction must be in (0,1).');
assert(config.falling_head_maximum_steps >= 1 && ...
    config.falling_head_maximum_steps == ...
    floor(config.falling_head_maximum_steps), ...
    'matdem_microplastic:InvalidFallingHeadSteps', ...
    'falling_head_maximum_steps must be a positive integer.');
end
