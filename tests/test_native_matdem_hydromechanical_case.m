function tests = test_native_matdem_hydromechanical_case
%TEST_NATIVE_MATDEM_HYDROMECHANICAL_CASE Pure/static native-model checks.
tests = functiontests(localfunctions);
end

function setupOnce(testCase)
projectRoot = string(fileparts(fileparts(mfilename('fullpath'))));
addpath(projectRoot);
setup_matdem_microplastic();
testCase.TestData.projectRoot = projectRoot;
end

function testLiteratureAndScenarioInputs(testCase)
config = native_matdem_hydromechanical_config( ...
    testCase.TestData.projectRoot);
expectedVoidRatio = 0.79 - 0.50 .* (0.79 - 0.46);
expectedPorosity = expectedVoidRatio ./ (1 + expectedVoidRatio);
verifyEqual(testCase, config.sand.d_min_m, 0.60e-3, ...
    'AbsTol', 1.0e-15);
verifyEqual(testCase, config.sand.d50_m, 0.82e-3, ...
    'AbsTol', 1.0e-15);
verifyEqual(testCase, config.sand.d_max_m, 1.18e-3, ...
    'AbsTol', 1.0e-15);
verifyEqual(testCase, config.sand.target_porosity, expectedPorosity, ...
    'AbsTol', 1.0e-15);
verifyEqual(testCase, config.microplastic.diameter_m ./ ...
    config.sand.d50_m, 0.30, 'AbsTol', 1.0e-15);
verifyFalse(testCase, config.microplastic.transport_enabled);
verifyEqual(testCase, config.random_seed, 1);
verifyLessThanOrEqual(testCase, config.random_seed, 1000);
end

function testResolvedParticleVolumes(testCase)
config = native_matdem_hydromechanical_config( ...
    testCase.TestData.projectRoot);
particles = generate_native_matdem_particle_distribution(config);
verifyGreaterThan(testCase, particles.sand_count, 10000);
verifyGreaterThan(testCase, particles.microplastic_count, 1000);
verifyLessThan(testCase, particles.total_count, 250000);
verifyLessThan(testCase, particles.solid_volume_relative_error, 1.0e-4);
verifyEqual(testCase, particles.actual_porosity, ...
    config.sand.target_porosity, 'AbsTol', 1.0e-4);
verifyEqual(testCase, ...
    particles.actual_microplastic_solid_volume_fraction, ...
    config.microplastic.solid_volume_fraction, 'AbsTol', 1.0e-4);
end

function testHydraulicBoundaryDefinition(testCase)
config = native_matdem_hydromechanical_config( ...
    testCase.TestData.projectRoot);
verifyEqual(testCase, config.fluid.head_difference_m ./ ...
    config.geometry.height_m, config.fluid.hydraulic_gradient, ...
    'AbsTol', 1.0e-15);
verifyEqual(testCase, config.fluid.pressure_difference_pa, ...
    config.fluid.density_kg_per_m3 .* ...
    config.fluid.gravity_m_per_s2 .* ...
    config.fluid.head_difference_m, 'RelTol', 1.0e-15);
verifyEqual(testCase, config.boundary.flow_direction, "top_to_bottom");
end

function testNativeCouplingWiring(testCase)
nativeDirectory = fullfile(testCase.TestData.projectRoot, ...
    "native_matdem");
initializeSource = fileread(fullfile(nativeDirectory, ...
    "native_matdem_initialize_pore3d.m"));
coupleSource = fileread(fullfile(nativeDirectory, ...
    "native_matdem_run_coupled_permeability.m"));
runnerSource = fileread(fullfile(testCase.TestData.projectRoot, ...
    "scripts", "run_native_matdem_hydromechanical_case.m"));
verifyNotEmpty(testCase, regexp(initializeSource, ...
    'p\s*=\s*pore3d\(d\)', 'once'));
verifyNotEmpty(testCase, regexp(initializeSource, ...
    'p\.setCouple\(''on''\)', 'once'));
verifyNotEmpty(testCase, regexp(coupleSource, ...
    'p\.fluid2Ball\(\)', 'once'));
verifyNotEmpty(testCase, regexp(coupleSource, ...
    'p\.d\.balance\(\)', 'once'));
verifyNotEmpty(testCase, regexp(coupleSource, ...
    'massBalanceRelativeError', 'once'));
verifyNotEmpty(testCase, regexp(runnerSource, ...
    'environment\.pore3d_path', 'once'));
verifyNotEmpty(testCase, regexp(runnerSource, ...
    'environment\.gpu_available', 'once'));
end

function testNativeSourceHasNoParserErrors(testCase)
nativeDirectory = fullfile(testCase.TestData.projectRoot, ...
    "native_matdem");
files = ["native_matdem_prepare_specimen.m"; ...
    "native_matdem_initialize_pore3d.m"; ...
    "native_matdem_run_coupled_permeability.m"];
for fileName = files.'
    issues = checkcode(fullfile(nativeDirectory, fileName), '-struct');
    if isempty(issues)
        continue
    end
    messages = lower(string({issues.message}));
    parserError = contains(messages, "syntax error") | ...
        contains(messages, "parse error") | ...
        contains(messages, "illegal use");
    verifyFalse(testCase, any(parserError), ...
        sprintf('Parser error reported in %s.', fileName));
end
end
