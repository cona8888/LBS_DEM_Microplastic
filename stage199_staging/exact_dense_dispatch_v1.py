"""Narrow internal dense-vector/determinant dispatch, unchanged kernels."""
from contextlib import contextmanager
from types import SimpleNamespace,FunctionType
import numpy as np
from numpy.linalg import _umath_linalg
import exact_trf_helpers_v1 as prior
ROOT,repair,compiled,batch=prior.ROOT,prior.repair,prior.compiled,prior.batch
constant,lsq=prior.constant,prior.lsq
clone=prior.clone
original_det=np.linalg.det
original_vector_norm=np.linalg.norm

def dense_norm(x,ord=None):
    # Private TRF domain: entry validates nine dense float64 variables, and
    # these internal vectors are generated by original NumPy operations.
    if ord is None:return np.sqrt(x.dot(x))
    if ord==np.inf:return prior.max_abs(x)
    raise ValueError('outside private dense TRF norm contract')

def vector_norm(x,ord=None,axis=None,keepdims=False):
    if ord is None and axis is None and keepdims is False and type(x) is np.ndarray and x.dtype==np.float64 and x.ndim==1:
        a=x.ravel(order='K');return np.sqrt(a.dot(a))
    return original_vector_norm(x,ord=ord,axis=axis,keepdims=keepdims)

def determinant(a):
    if type(a) is np.ndarray and a.dtype==np.float64 and a.ndim==3 and a.shape[1:]==(6,6):
        return _umath_linalg.det(a,signature='d->d')
    return original_det(a)

svd_prior=prior.prior.prior
def svd(a,full_matrices=True):
    if not (type(a) is np.ndarray and a.dtype==np.float64 and a.shape==(9,9) and full_matrices is False):return svd_prior.original_svd(a,full_matrices=full_matrices)
    if not prior.all_finite(a):raise ValueError('array must not contain infs or NaNs')
    u,s,v,info=svd_prior.lapack(a,compute_uv=True,lwork=svd_prior.worksize,full_matrices=False,overwrite_a=False)
    if info>0:raise np.linalg.LinAlgError('SVD did not converge')
    if info<0:
        if info==-4:raise ValueError('A has a NaN entry')
        raise ValueError(f'illegal value in {-info}th argument of internal gesdd')
    return u,s,v

trust=clone(prior.trust,{'norm':dense_norm})
trf_no_bounds=clone(prior.trf_no_bounds,{'norm':dense_norm,'svd':svd,'solve_lsq_trust_region':trust})
least_squares=clone(prior.least_squares,{'trf':SimpleNamespace(trf_no_bounds=trf_no_bounds)})
np_private=SimpleNamespace(**vars(np));np_private.linalg=SimpleNamespace(**vars(np.linalg));np_private.linalg.det=determinant;np_private.linalg.norm=vector_norm
scalar_solve=clone(batch.scalar_solve,{'np':np_private})

@contextmanager
def scope(mode):
    if mode in ('baseline','direct'):
        with prior.scope('baseline' if mode=='baseline' else 'compiled_direct'):yield
    elif mode=='compiled_direct':
        saved=repair.prior.least_squares;scalar=batch.original.scalar_solve;repair.prior.least_squares=least_squares;batch.original.scalar_solve=scalar_solve
        try:
            with compiled.scope(True):yield
        finally:repair.prior.least_squares=saved;batch.original.scalar_solve=scalar
    else:raise ValueError('explicit benchmark mode required')
